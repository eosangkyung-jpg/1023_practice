"""강남·잠실 막차 지도 — 상권에 있을 때 2호선 막차를 타려면 늦어도 몇 시에 나와야 하나.

실행:  streamlit run app.py   → http://localhost:8501
(카카오 콘솔 JavaScript SDK 도메인에 http://localhost:8501 등록 필요. 8502·IP·127.0.0.1 로 열면 지도가 안 떠요)
.env 를 고쳤다면 Ctrl+C 후 다시 streamlit run.
"""
import math
import os
from pathlib import Path

import pandas as pd
import streamlit as st
from dotenv import load_dotenv

from make_map import kakao_map_html

# ── 디자인 값은 여기 한 곳에서만 ────────────────────────────
STYLE = {
    "제목": "🚇 막차 지도 — 강남·잠실",
    "지도_높이": 520,
    # 도보 시간(분)이 이 값 이하이면 이 색 (위에서부터 차례로)
    "박스_색": [(10, "#2E7D32", "🟩 10분 이내"), (15, "#EF6C00", "🟧 10~15분"), (999, "#C62828", "🟥 15분 넘음")],
    "박스_투명도": 0.25,
    "박스_선두께": 2,
}

# ── 계산 가정 (화면 캡션에도 그대로 보여 줌) ─────────────────
걸음_속도 = {"보통 (분당 67m)": 67, "천천히 (분당 50m)": 50}
역_안_이동_분 = {"강남": 3, "잠실": 4}  # 출구 → 승강장 (가정값)
여유_분 = 3
요일_코드 = {"평일": "DAY", "토요일": "SAT", "일요일·공휴일": "END"}
출처 = (
    "출처: 서울교통공사 서울 도시철도 열차운행시각표 (공공데이터포털, 2026-09-01 기준) · "
    "서울시 상권분석서비스 영역-상권 (서울 열린데이터광장, 2026-09-11 갱신) · 출입구 좌표: 카카오 로컬 API"
)

폴더 = Path(__file__).parent / "data"
load_dotenv(override=True)


@st.cache_data
def 읽기(이름):
    return pd.read_csv(폴더 / 이름, encoding="utf-8-sig")


def 분_표시(분):
    """1461.5 → '00:21' (초는 버림)."""
    분 = math.floor(분)
    return f"{(분 // 60) % 24:02d}:{분 % 60:02d}"


def 박스_색(도보_분):
    for 한도, 색, _ in STYLE["박스_색"]:
        if 도보_분 <= 한도:
            return 색
    return STYLE["박스_색"][-1][1]


st.set_page_config(page_title="막차 지도", page_icon="🚇", layout="wide")
st.title(STYLE["제목"])
st.write("상권에 있을 때 **2호선 막차**를 타려면 늦어도 몇 시에 나와야 하는지 알려 줘요.")

막차표, 출입구, 상권 = 읽기("last_train.csv"), 읽기("exits.csv"), 읽기("areas.csv")

# ── 사이드바 필터 ───────────────────────────────────────────
with st.sidebar:
    st.header("조건")
    출발역 = st.radio("지금 있는 곳 근처 역", ["강남", "잠실"], horizontal=True)
    목적지들 = sorted(막차표.loc[막차표["출발역"] == 출발역, "목적지역"].unique())
    목적지 = st.selectbox("내릴 역", 목적지들, index=목적지들.index("홍대입구") if "홍대입구" in 목적지들 else 0)
    요일 = st.radio("요일", list(요일_코드), horizontal=True)
    속도_이름 = st.radio("걸음 속도", list(걸음_속도))
    구분들 = sorted(상권["상권구분"].unique())
    고른_구분 = st.multiselect("상권 종류", 구분들, default=구분들)

# ── 필터된 표 view 하나에서 숫자·지도·표를 모두 만든다 ────────
막차 = 막차표[(막차표["출발역"] == 출발역) & (막차표["목적지역"] == 목적지) & (막차표["주중주말"] == 요일_코드[요일])]
if 막차.empty:
    st.info(f"{출발역}에서 {목적지}까지 갈아타지 않고 가는 {요일} 열차가 없어요")
    st.stop()
막차 = 막차.iloc[0]

view = 상권[(상권["역"] == 출발역) & 상권["상권구분"].isin(고른_구분)].copy()
view["도보_분"] = (view["도보거리_m"] / 걸음_속도[속도_이름]).apply(math.ceil)
view["나와야_분"] = 막차["출발_분"] - view["도보_분"] - 역_안_이동_분[출발역] - 여유_분
view["나와야 할 시각"] = view["나와야_분"].map(분_표시)
view = view.sort_values("나와야_분")

칸1, 칸2, 칸3 = st.columns(3)
칸1.metric("막차 출발", 막차["막차_시각"], help=f"{막차['행선지']}행 · {목적지} {막차['목적지_도착']} 도착")
if view.empty:
    칸2.metric("가장 먼 상권 도보", "-")
    칸3.metric("늦어도 나와야 할 시각", "-")
else:
    가장_먼 = view.iloc[0]
    칸2.metric("가장 먼 상권 도보", f"{가장_먼['도보_분']}분", help=f"{가장_먼['상권명']} → {가장_먼['기준_출구']} 출구")
    칸3.metric("늦어도 나와야 할 시각", 가장_먼["나와야 할 시각"], help="이 역 근처 상권 중 가장 먼 곳 기준")
st.caption(f"{막차['행선지']}행 열차 · {목적지}에 {막차['목적지_도착']} 도착 (약 {막차['소요_분']}분)")

if view.empty:
    st.info("조건에 맞는 곳이 없어요")
else:
    js키 = os.getenv("KAKAO_JS_KEY")
    if not js키:
        st.error(".env 에 KAKAO_JS_KEY 가 없어요")
    else:
        박스들 = [
            {
                "이름": 줄["상권명"],
                "남서_위도": 줄["남서_위도"], "남서_경도": 줄["남서_경도"],
                "북동_위도": 줄["북동_위도"], "북동_경도": 줄["북동_경도"],
                "색": 박스_색(줄["도보_분"]),
                "투명도": STYLE["박스_투명도"], "선두께": STYLE["박스_선두께"],
                "줄들": [f"늦어도 {줄['나와야 할 시각']} 출발",
                         f"{줄['기준_출구']} 출구까지 도보 {줄['도보_분']}분",
                         f"{줄['상권구분']} · 한 변 약 {줄['한변_m']}m"],
            }
            for _, 줄 in view.iterrows()
        ]
        문들 = 출입구[출입구["역"] == 출발역]
        마커들 = [
            {"이름": f"{출발역}역 {줄['출구']} 출구", "위도": 줄["위도"], "경도": 줄["경도"],
             "줄들": [f"카카오 등록: {줄['등록_노선']}"]}
            for _, 줄 in 문들.iterrows()
        ]
        st.iframe(kakao_map_html(js키, 마커들, 박스들, STYLE["지도_높이"]), height=STYLE["지도_높이"] + 40)
        st.caption("범례: " + " · ".join(설명 for _, _, 설명 in STYLE["박스_색"])
                   + " (상권 박스 색 = 출구까지 도보 시간) · 📍 = 출입구")

    st.dataframe(
        view[["상권명", "상권구분", "기준_출구", "도보거리_m", "도보_분", "나와야 할 시각"]]
        .rename(columns={"기준_출구": "가까운 출구", "도보거리_m": "도보 거리(m)", "도보_분": "도보(분)"}),
        hide_index=True, width="stretch",
    )

st.caption(
    f"도보 시간은 상권 박스에서 가장 먼 꼭짓점 → 가까운 출구까지 **가로+세로 거리**(건물을 가로지르지 않는 격자 경로)로 계산한 예상치예요. "
    f"역 안 이동 {출발역} {역_안_이동_분[출발역]}분 · 여유 {여유_분}분을 뺐어요. "
    "**갈아타지 않고 한 번에 가는 열차** 기준이고, 열차 지연은 반영되지 않아요. 시각표 기준 데이터예요."
)
st.caption(출처)
